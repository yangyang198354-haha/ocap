import re
from pathlib import Path

from django.test import TestCase

from apps.accounts.models import User
from apps.accounts.services import THEME_KEY_RE, AccountService
from apps.core.errors import ApiError

MIGRATION = Path(__file__).resolve().parents[2] / "apps/accounts/migrations/0002_user_theme_key.py"


class ThemeKeyRuleTests(TestCase):
    def test_tc_unit_001_valid_keys_match(self):
        """TC-UNIT-001 AC-078-01：合法 key（2~32 位小写字母开头，含数字 _ -）通过。"""
        for key in ("bento", "neon", "terminal", "ab", "a" + "9" * 31, "test-style_d"):
            self.assertIsNotNone(THEME_KEY_RE.match(key), key)

    def test_tc_unit_002_invalid_keys_rejected(self):
        """TC-UNIT-002 AC-080-03：空、1 字符、33 字符、大写、空白、换行结尾、数字开头均不匹配。"""
        for key in ("", "a", "a" * 33, "Neon", "ne on", "neon\n", "1neon", "-neon", "ne.on", "néon"):
            self.assertIsNone(THEME_KEY_RE.match(key), repr(key))


class SetThemeServiceTests(TestCase):
    def _user(self, n="1"):
        return User.objects.create(account_no=f"7000000{n}", phone=f"1370000000{n}")

    def test_tc_unit_003_default_is_null(self):
        """TC-UNIT-003 AC-075-01：新建账号 theme_key 为 NULL（语义 = 默认 B）。"""
        self.assertIsNone(self._user().theme_key)

    def test_tc_unit_004_set_theme_persists_only_that_user(self):
        """TC-UNIT-004 AC-078-03：set_theme 只改该用户，另一用户保持 NULL。"""
        a, b = self._user("1"), self._user("2")
        AccountService.set_theme(a, "terminal")
        self.assertEqual(User.objects.get(pk=a.pk).theme_key, "terminal")
        self.assertIsNone(User.objects.get(pk=b.pk).theme_key)

    def test_tc_unit_005_invalid_input_raises_and_keeps_value(self):
        """TC-UNIT-005 AC-080-03：非法值抛 ApiError(INVALID_VALUE, 400)，原值不变；None/数字/列表同样拒绝。"""
        user = self._user()
        AccountService.set_theme(user, "neon")
        for bad in ("Neon", "", None, 5, ["neon"], {"a": 1}, "a" * 40):
            with self.assertRaises(ApiError) as ctx:
                AccountService.set_theme(user, bad)
            self.assertEqual(ctx.exception.code, "INVALID_VALUE")
            self.assertEqual(ctx.exception.status_code, 400)
        self.assertEqual(User.objects.get(pk=user.pk).theme_key, "neon")

    def test_tc_unit_006_unregistered_but_wellformed_key_is_accepted(self):
        """TC-UNIT-006 AC-086-01：后端只校验格式，不维护启用集合（风格下线由客户端回退，ADR-025）。"""
        user = self._user()
        AccountService.set_theme(user, "retired-style")
        self.assertEqual(User.objects.get(pk=user.pk).theme_key, "retired-style")


class ThemeMigrationFileTests(TestCase):
    def test_tc_unit_007_migration_is_handwritten_single_addfield(self):
        """TC-UNIT-007 画像 P6/P8：迁移手写（无 Generated by Django）、依赖 0001、仅一个可空 AddField。"""
        text = MIGRATION.read_text(encoding="utf-8")
        self.assertNotIn("Generated by Django", text)
        self.assertIn('("accounts", "0001_initial")', text.replace("'", '"'))
        self.assertEqual(len(re.findall(r"migrations\.AddField", text)), 1)
        self.assertIn("theme_key", text)
        self.assertRegex(text, r"null=True")
